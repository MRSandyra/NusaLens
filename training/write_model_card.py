"""Phase 6: assemble the model card from the real training and evaluation artifacts."""
import json

from nusalens.config import PROJECT_ROOT

MODEL_DIR = PROJECT_ROOT / "models" / "e5-nusalens-v1"


def main() -> None:
    train_run = json.loads((PROJECT_ROOT / "reports" / "raw" / "06_train_run.json").read_text(encoding="utf-8"))
    finetune_eval = json.loads((PROJECT_ROOT / "reports" / "raw" / "06_finetune_eval.json").read_text(encoding="utf-8"))
    split_stats = json.loads((PROJECT_ROOT / "data" / "silver" / "split_stats.json").read_text(encoding="utf-8"))
    filter_stats = json.loads((PROJECT_ROOT / "data" / "silver" / "pairs_filter_stats.json").read_text(encoding="utf-8"))

    c1 = finetune_eval["stock_e5_small_dense"]
    c2 = finetune_eval["finetuned_e5_small_dense"]
    c3 = finetune_eval["finetuned_e5_small_rrf_rerank"]
    c4 = finetune_eval["larger_stock_e5_base_dense"]
    mat = finetune_eval["matryoshka"]

    lines = [
        "# e5-nusalens-v1",
        "",
        "Fine-tuned `intfloat/multilingual-e5-small` for Indonesian public-data retrieval.",
        "",
        "## Base model",
        "",
        "`intfloat/multilingual-e5-small` (118M parameters, 384-dim output, MIT license).",
        "",
        "## Training data",
        "",
        "Synthetic (question, chunk) pairs generated by a local LLM (`qwen2.5:3b-instruct` via Ollama) over "
        f"the NusaLens corpus, quality-filtered and deduplicated, then split by `doc_id` at 80/10/10 "
        "with every document referenced by the frozen Phase 4 golden set forced into the test split. "
        "No license restriction beyond the source corpus (Indonesian Wikipedia, CC BY-SA).",
        "",
        "| Stage | Count |",
        "|---|---|",
        f"| Raw generated | {filter_stats['raw']} |",
        f"| After word-count filter (5-40 words) | {filter_stats['after_word_count']} |",
        f"| After meta-phrase filter | {filter_stats['after_meta_phrase']} |",
        f"| After round-trip BM25 top-50 filter | {filter_stats['after_round_trip_bm25_top50']} |",
        f"| After near-duplicate filter (cosine > 0.97) | {filter_stats['after_dedup_0.97']} |",
        "",
        f"Split: {split_stats['train_docs']} train docs ({split_stats['train_pairs']} pairs), "
        f"{split_stats['val_docs']} val docs ({split_stats['val_pairs']} pairs), "
        f"{split_stats['test_docs']} test docs ({split_stats['test_pairs']} pairs), "
        f"{split_stats['forced_golden_docs_in_test']} of the test docs forced in because the golden set references them. "
        f"{split_stats['leakage_check']}",
        "",
        "## Training",
        "",
        "`MultipleNegativesRankingLoss` wrapped in `MatryoshkaLoss` (dims 384/256/128/64), 3 mined hard negatives per "
        "positive (`range_min=10, range_max=50, max_score=0.95`), `BatchSamplers.NO_DUPLICATES`.",
        "",
        "| Hyperparameter | Value |",
        "|---|---|",
        f"| Batch size | {train_run['batch_size']} |",
        f"| Effective batch size | {train_run['effective_batch']} |",
        f"| Used CachedMultipleNegativesRankingLoss | {train_run['used_cached_loss']} |",
        f"| Epochs | {train_run['epochs']} |",
        f"| Learning rate | {train_run['learning_rate']} |",
        f"| Warmup ratio | {train_run['warmup_ratio']} |",
        f"| Matryoshka dims | {train_run['matryoshka_dims']} |",
        f"| Peak VRAM | {train_run['peak_vram_mb']} MB |",
        f"| Wall time | {train_run['wall_time_s']} s |",
        f"| Train triplets | {train_run['n_train_triplets']} |",
        "",
        "## Evaluation (frozen Phase 4 golden set, 70 DOC/HYBRID items, k=10)",
        "",
        "| Condition | Recall@1 | Recall@10 | MRR@10 | nDCG@10 |",
        "|---|---|---|---|---|",
        f"| 1. stock e5-small, dense | {c1['recall_at_1']:.1%} | {c1['recall_at_10']:.1%} | {c1['mrr_at_10']:.3f} | {c1['ndcg_at_10']:.3f} |",
        f"| 2. fine-tuned e5-small, dense | {c2['recall_at_1']:.1%} | {c2['recall_at_10']:.1%} | {c2['mrr_at_10']:.3f} | {c2['ndcg_at_10']:.3f} |",
        f"| 3. fine-tuned e5-small, RRF+rerank (full pipeline) | {c3['recall_at_1']:.1%} | {c3['recall_at_10']:.1%} | {c3['mrr_at_10']:.3f} | {c3['ndcg_at_10']:.3f} |",
        f"| 4. larger stock model (multilingual-e5-base, 278M), dense | {c4['recall_at_1']:.1%} | {c4['recall_at_10']:.1%} | {c4['mrr_at_10']:.3f} | {c4['ndcg_at_10']:.3f} |",
        "",
        "### Matryoshka dimension truncation",
        "",
        "| Dim | nDCG@10 | Bytes/vector | Storage saving |",
        "|---|---|---|---|",
    ]
    for dim in sorted(mat.keys(), key=int, reverse=True):
        m = mat[dim]
        lines.append(f"| {dim} | {m['ndcg_at_10']:.3f} | {m['storage_bytes_per_vector']} | {m['storage_saving_pct']}% |")

    lines += [
        "",
        "## Limitations",
        "",
        "Trained on Indonesian Wikipedia and World Bank indicator text only; not evaluated on domains outside "
        "the NusaLens corpus (government regulation text, legal documents). Synthetic question generation uses "
        "a small instruct model and inherits its biases toward factual, Wikipedia-style phrasing.",
        "",
        "Not pushed to the Hugging Face Hub (would require git-adjacent tooling); upload manually if needed.",
    ]

    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    (MODEL_DIR / "README.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {MODEL_DIR / 'README.md'}")


if __name__ == "__main__":
    main()
